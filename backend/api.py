# ------------------------------------------------------------------
# CORS-safe global exception handler.
# Starlette's CORSMiddleware only adds headers to 2xx / 4xx responses
# generated by the routing layer. Unhandled 500s bypass it — the
# browser then sees no CORS header and reports a CORS error instead
# of the actual 500.  This handler intercepts every unhandled
# exception, returns a proper JSON 500, and manually injects the
# Access-Control-Allow-Origin header so the browser can read the
# error response without a CORS block.
# ------------------------------------------------------------------
CORS_ALLOW_ORIGINS = set(_settings.allowed_origins)

@app.exception_handler(Exception)
async def global_cors_safe_exception_handler(request: Request, exc: Exception):
    origin = request.headers.get("origin", "")
    headers = {}
    if origin in CORS_ALLOW_ORIGINS:
        headers["Access-Control-Allow-Origin"] = origin
        headers["Access-Control-Allow-Credentials"] = "true"
        headers["Access-Control-Allow-Methods"] = "*"
        headers["Access-Control-Allow-Headers"] = "*"
    error_type = type(exc).__name__
    error_msg = str(exc)
    # Truncate very long tracebacks in the response body
    if len(error_msg) > 400:
        error_msg = error_msg[:400] + "..."
    print(f"UNHANDLED EXCEPTION [{error_type}]: {error_msg}")
    return JSONResponse(
        status_code=500,
        content={"error": error_type, "detail": error_msg},
        headers=headers,
    )


