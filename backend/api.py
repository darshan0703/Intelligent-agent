@app.post("/stt")
async def speech_to_text(
    file: UploadFile = File(...)
):
    whisper_cli = os.path.expanduser(
        "~/whisper.cpp/build/bin/whisper-cli"
    )

    whisper_model = os.path.expanduser(
        "~/whisper.cpp/models/ggml-small.en.bin"
    )

    ffmpeg = "/opt/homebrew/bin/ffmpeg"

    print("\n" + "=" * 80)
    print("STT REQUEST")
    print("=" * 80)

    print(
        "WHISPER CLI:",
        whisper_cli,
    )

    print(
        "WHISPER MODEL:",
        whisper_model,
    )

    print(
        "FFMPEG:",
        ffmpeg,
    )

    print(
        "UPLOADED FILE:",
        file.filename,
    )

    print(
        "CONTENT TYPE:",
        file.content_type,
    )

    if not Path(whisper_cli).exists():
        print("ERROR: Whisper CLI not found.")

        return {
            "success": False,
            "message": "Whisper CLI not found.",
        }

    if not Path(whisper_model).exists():
        print("ERROR: Whisper model not found.")

        return {
            "success": False,
            "message": "Whisper model not found.",
        }

    if not Path(ffmpeg).exists():
        print("ERROR: FFmpeg not found.")

        return {
            "success": False,
            "message": "FFmpeg not found.",
        }

    try:
        with tempfile.TemporaryDirectory() as temp_dir:
            temp_dir = Path(temp_dir)

            input_file = temp_dir / "input.webm"
            wav_file = temp_dir / "input.wav"

            print("READING UPLOADED AUDIO...")

            audio_data = await file.read()

            print(
                "AUDIO SIZE:",
                len(audio_data),
                "bytes",
            )

            input_file.write_bytes(
                audio_data
            )

            print("STARTING FFMPEG...")

            ffmpeg_result = subprocess.run(
                [
                    ffmpeg,
                    "-y",
                    "-i",
                    str(input_file),
                    "-ar",
                    "16000",
                    "-ac",
                    "1",
                    "-c:a",
                    "pcm_s16le",
                    str(wav_file),
                ],
                capture_output=True,
                text=True,
                timeout=20,
            )

            print(
                "FFMPEG FINISHED:",
                ffmpeg_result.returncode,
            )

            if ffmpeg_result.returncode != 0:
                print(
                    "FFMPEG ERROR:"
                )

                print(
                    ffmpeg_result.stderr
                )

                return {
                    "success": False,
                    "message": "Audio conversion failed.",
                }

            print(
                "WAV CREATED:",
                wav_file.exists(),
            )

            if wav_file.exists():
                print(
                    "WAV SIZE:",
                    wav_file.stat().st_size,
                    "bytes",
                )

            print(
                "STARTING WHISPER..."
            )

            whisper_result = subprocess.run(
                [
                    whisper_cli,
                    "-m",
                    whisper_model,
                    "-f",
                    str(wav_file),
                    "-l",
                    "en",
                    "-nt",
                    "-np",
                ],
                capture_output=True,
                text=True,
                timeout=30,
            )

            print(
                "WHISPER FINISHED:",
                whisper_result.returncode,
            )

            if whisper_result.stderr:
                print(
                    "WHISPER STDERR:"
                )

                print(
                    whisper_result.stderr
                )

            if whisper_result.returncode != 0:
                print(
                    "WHISPER ERROR"
                )

                return {
                    "success": False,
                    "message": "Speech recognition failed.",
                }

            transcript = (
                whisper_result.stdout
                .strip()
            )

            print(
                "WHISPER TRANSCRIPT:",
                transcript,
            )

            print("=" * 80 + "\n")

            return {
                "success": True,
                "text": transcript,
            }

    except subprocess.TimeoutExpired as e:
        print(
            "STT TIMEOUT:",
            repr(e),
        )

        return {
            "success": False,
            "message": "Speech recognition timed out.",
        }

    except Exception as e:
        print(
            "STT ERROR:",
            repr(e),
        )

        return {
            "success": False,
            "message": "Speech recognition failed.",
        }
