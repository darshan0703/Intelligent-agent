@app.post("/message")
def message(request: MessageRequest):
    print("USER MESSAGE:", request.message)

    # Clear any response left by a previous agent turn.
    conversation_context.pop(
        "_last_kiosk_response",
        None,
    )

    msg_clean = request.message.lower().strip()

    # Fast-path for direct category requests (1ms response)
    category_map = {
        "burger": "burger",
        "burgers": "burger",
        "whopper": "burger",
        "drink": "drink",
        "drinks": "drink",
        "beverage": "drink",
        "beverages": "drink",
        "side": "side",
        "sides": "side",
        "fries": "side",
        "dessert": "dessert",
        "desserts": "dessert",
    }
    for kw, cat in category_map.items():
        if f"i want a {kw}" in msg_clean or f"i want {kw}" in msg_clean or msg_clean == kw:
            from services.menuservice import handle_category
            kiosk_resp = handle_category(cat, conversation_context)
            if hasattr(kiosk_resp, "model_dump"):
                return kiosk_resp.model_dump()
            elif isinstance(kiosk_resp, dict):
                return kiosk_resp

    try:
        agent_response = run_cashier_agent(
            request.message,
            conversation_context,
        )
    except Exception as exc:
        print(f"CASHIER AGENT ERROR: {exc}")
        agent_response = "Welcome to Burger King! How can I help you today?"

    kiosk_response = conversation_context.pop(
        "_last_kiosk_response",
        None,
    )

    if kiosk_response is not None:
        kiosk_response.message = agent_response
        return kiosk_response.model_dump()

    return {
        "screen": conversation_context.get("current_screen"),
        "message": agent_response or "Welcome to Burger King! What would you like to order?",
        "cart": conversation_context.get(
            "cart",
            [],
        ),
    }


