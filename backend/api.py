_tts_cache: dict[str, bytes] = {}

@app.post("/tts")
def text_to_speech(request: dict):
    text = request.get("text")

    print("TTS REQUEST:", text)

    if not text:
        return Response(
            content=b"",
            media_type="audio/wav",
            status_code=400,
        )

    if text in _tts_cache:
        print("TTS CACHE HIT:", text[:30])
        return Response(
            content=_tts_cache[text],
            media_type="audio/wav",
        )

    try:
        print("GENERATING KOKORO AUDIO...")

        generator = tts_pipeline(
            text,
            voice="af_heart",
        )

        audio_segments = []

        for _, _, audio in generator:
            audio_segments.append(
                np.asarray(audio)
            )

        if not audio_segments:
            raise RuntimeError(
                "Kokoro generated no audio."
            )

        audio_data = np.concatenate(
            audio_segments
        )

        audio_buffer = io.BytesIO()

        sf.write(
            audio_buffer,
            audio_data,
            24000,
            format="WAV",
        )

        audio_buffer.seek(0)

        audio_bytes = audio_buffer.read()

        if len(_tts_cache) < 200:
            _tts_cache[text] = audio_bytes

        print(
            "KOKORO AUDIO GENERATED:",
            len(audio_bytes),
            "bytes",
        )

        return Response(
            content=audio_bytes,
            media_type="audio/wav",
        )

    except Exception as e:
        print(
            "KOKORO TTS ERROR:",
            repr(e),
        )

        return Response(
            content=b"TTS generation failed",
            media_type="text/plain",
            status_code=500,
        )


