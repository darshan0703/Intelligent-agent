# =========================================================

def handle_category(
    category,
    conversation_context
):

    category_map = {
        "beverage": "drink",
        "beverages": "drink",
        "drinks": "drink",
        "burger": "burger",
        "burgers": "burger",
        "side": "side",
        "sides": "side",
        "dessert": "dessert",
        "desserts": "dessert"
    }

    category = category_map.get(
        category.lower(),
        category.lower()
    )

    conversation_context["last_category"] = category

    if category == "burger":

        return handle_burger_selection(
            "both",
            conversation_context
        )

    if category == "drink":

        return handle_drink_selection(
            conversation_context
        )

    if category == "side":

        return handle_side_selection(
            conversation_context
        )

    if category == "dessert":

        return handle_dessert_selection(
            conversation_context
        )

    return "Unknown category."


