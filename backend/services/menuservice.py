def handle_burger_selection(
    burger_type,
    conversation_context
):

    burgers = get_category("burger")

    if not burgers:

        return KioskResponse(
            screen=ScreenTypes.RECOMMENDED_BURGERS,
            message=(
                "Sorry, no burgers are "
                "available right now."
            ),
            data={}
        )

    # -----------------------------------------------------
    # BUILD ONE COMBINED MASTER DATASET
    #
    # The frontend owns the Veg / Non-Veg filter.
    # -----------------------------------------------------

    cart = conversation_context.get("cart", []) if conversation_context else []
    recommendation_data = (
        build_burger_recommendation_data(
            burgers,
            cart=cart
        )
    )

 
    print("BURGER MASTER RECOMMENDATION DATA")
   

    total = (
        len(recommendation_data["priority"])
        + len(recommendation_data["premium"])
        + len(recommendation_data["additional"])
    )

    print(
        "PRIORITY:",
        [
            item["name"]
            for item in recommendation_data["priority"]
        ]
    )

    print(
        "PREMIUM:",
        [
            item["name"]
            for item in recommendation_data["premium"]
        ]
    )

    print(
        "ADDITIONAL:",
        [
            item["name"]
            for item in recommendation_data["additional"]
        ]
    )

    print("TOTAL:", total)

    print("==============================\n")

    # -----------------------------------------------------
    # SELECT DATASET ACCORDING TO USER'S ACTIVE PREFERENCE
    # -----------------------------------------------------

    active_pref = conversation_context.get("food_preference")
    if burger_type in ("veg", "non_veg", "both"):
        chosen_type = burger_type
    elif active_pref in ("veg", "non_veg"):
        chosen_type = active_pref
    else:
        chosen_type = "both"

    chosen = recommendation_data.get(chosen_type, recommendation_data["both"])

    selected = (
        chosen["priority"]
        + chosen["premium"]
        + chosen["additional"]
    )

    conversation_context["last_offer"] = [
        item["name"]
        for item in selected
    ]

    # -----------------------------------------------------
    # NATURAL OPENING MESSAGE
    # -----------------------------------------------------

    message_parts = []

    if chosen["priority"]:

        message_parts.append(
            f"I'd recommend our "
            f"{chosen['priority'][0]['name']}."
        )

    if chosen["premium"]:

        message_parts.append(
            f"If you're looking for something premium, "
            f"we also have our "
            f"{chosen['premium'][0]['name']}."
        )

    if chosen["additional"]:

        message_parts.append(
            "We also have more options in burgers "
            "if you'd like to explore them."
        )

    message = " ".join(
        message_parts
    )

    # -----------------------------------------------------
    # RETURN ONE MASTER DATASET
    # -----------------------------------------------------

    return KioskResponse(
        screen=ScreenTypes.RECOMMENDED_BURGERS,
        message=message,
        data={
            "selected_type": chosen_type,

            "all_burgers": burgers,

            "priority": chosen["priority"],
            "premium": chosen["premium"],
            "additional": chosen["additional"],
            "both": recommendation_data["both"],
            "veg": recommendation_data["veg"],
            "non_veg": recommendation_data["non_veg"]
        }
    )


